#!/bin/bash
# Штатная точка входа OpenHands: выполняется при каждом старте работы с
# репозиторием, в том числе после пересоздания контейнера.
#
# Раньше автозапуск жил в ~/.bashrc и /etc/profile.d — эти каталоги
# сбрасываются к образу при пересоздании контейнера, поэтому сервер
# оставался лежать. Каталог .openhands лежит в /workspace, а /workspace —
# постоянный том, единственный во всём окружении.
#
# Скрипт намеренно не блокирует запуск агента: сервер поднимается в фоне.

cd "$(dirname "$0")/.." || exit 0
./autostart.sh >/dev/null 2>&1 &
exit 0
